"""Measure every image used in covers/sheets.js and write covers/sheet-images.js.

    python tools/sheet_images.py

For each image: aspect ratio, the uniform padding baked into the file
(black/grey bands from the web slides) so the A4 sheets can trim it, and how
the image meets the paper:
  c : colour of its outer edge (hex)       f : 1 if that edge is one flat colour
  l : mean lightness 0–1 (dark images turn the sheet dark)
Re-run after adding or changing images in sheets.js.
"""
import json, re
from pathlib import Path
from PIL import Image, ImageStat

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'covers' / 'sheets.js'
OUT = ROOT / 'covers' / 'sheet-images.js'
MAX_TRIM = 0.45          # never trim more than this per side (some web slides pad a photo by ~40%)
TOL = 7                  # spread allowed inside a dark band
FLAT = 1.2               # spread of a digitally flat band (photos have more grain than this)
PLATE = .6               # ring share in the padding colour that makes a slide (same value in covers/index.html)
DARK = 70                # a band this dark counts as padding even with a little noise


def band(im, side):
    """fraction of the image, from `side`, that is one flat colour"""
    w, h = im.size
    n = h if side in 'tb' else w
    edge = None
    limit = int(n * MAX_TRIM)
    for k in range(limit):
        if side == 't': box = (0, k, w, k + 1)
        elif side == 'b': box = (0, h - k - 1, w, h - k)
        elif side == 'l': box = (k, 0, k + 1, h)
        else: box = (w - k - 1, 0, w - k, h)
        st = ImageStat.Stat(im.crop(box))
        mean = st.mean
        # padding = digitally flat (no photo grain) or a dark band; studio backdrops are left alone
        flat = max(st.stddev) <= FLAT
        dark = max(st.stddev) <= TOL and max(mean) < DARK
        if not (flat or dark): return k / n
        if edge is None: edge = mean
        elif max(abs(a - b) for a, b in zip(mean, edge)) > TOL: return k / n
    return limit / n


def measure(path):
    im = Image.open(path)
    im.seek(0)
    w, h = im.size
    small = im.convert('RGBA').convert('RGB') if im.mode == 'P' else im.convert('RGB')
    small.thumbnail((400, 400))
    t, b, l, r = (band(small, s) for s in 'tblr')
    if t + b > .7 or l + r > .7: t = b = l = r = 0   # mostly flat image — leave it alone
    W, H = small.size
    inner = small.crop((round(l * W), round(t * H), round(W - r * W), round(H - b * H)))
    pad, flat = edge(small)                      # the file's own outer ring
    if flat > .9 and any((t, b, l, r)):
        # a padded slide: does the content carry on in the padding colour right up to the cut?
        # (a slide — yes, give it a mat of that colour; a photo pasted on grey — no, it bleeds)
        c, f = pad, edge(inner, pad, 26)[1]
    else:
        c, f = edge(inner)
    # a photograph: cut a little past the band, so no sliver of a thin divider line survives.
    # a slide (flat edge, it will get a mat): the band stops at its content, so cut nothing more.
    if f < PLATE:
        t, b, l, r = (min(MAX_TRIM, x + .006) if x > 0 else 0 for x in (t, b, l, r))
    else:   # keep a hair of padding round the content; the mat adds the rest
        t, b, l, r = (max(0, x - .004) for x in (t, b, l, r))
    lum = ImageStat.Stat(small.convert('L')).mean[0] / 255
    return {'a': round(w / h, 4), 't': [round(t, 4), round(r, 4), round(b, 4), round(l, 4)],
            'c': c, 'f': f, 'l': round(lum, 3)}


def rgb(h): return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def edge(im, ref=None, tol=14):
    """colour of the outer ring, and the share of it that is one flat colour
    (the ring's own mean, or `ref`) — a slide background, not a photo"""
    w, h = im.size
    k = max(2, round(min(w, h) * .02))
    px = []
    for box in ((0, 0, w, k), (0, h - k, w, h), (0, 0, k, h), (w - k, 0, w, h)):
        px += list(im.crop(box).get_flattened_data())
    n = len(px)
    mean = [sum(p[i] for p in px) / n for i in range(3)]
    ref = rgb(ref) if ref else mean
    near = sum(1 for p in px if max(abs(p[i] - ref[i]) for i in range(3)) < tol) / n
    return '#%02x%02x%02x' % tuple(round(v) for v in mean), round(near, 2)


def main():
    js = SRC.read_text(encoding='utf8')
    out = {}
    # walk projects in order: dir, then every s:'file' until the next dir
    cur = None
    for m in re.finditer(r"dir:'([^']+)'|\bs:'([^']+)'", js):
        if m.group(1): cur = m.group(1); continue
        f = m.group(2)
        key = f if f.startswith('/') else f'/assets/img/projects/{cur}/{f}'
        if key in out: continue
        p = ROOT / key.lstrip('/')
        if not p.exists():
            print('missing', key); continue
        out[key] = measure(p)
    OUT.write_text('/* generated by tools/sheet_images.py — aspect ratio + baked-in padding [top,right,bottom,left], edge colour c, edge flatness f, lightness l */\n'
                   'const SHEET_IMG = ' + json.dumps(out, separators=(',', ':')) + ';\n', encoding='utf8', newline='\n')
    trimmed = sum(1 for v in out.values() if any(v['t']))
    print(len(out), 'images,', trimmed, 'with padding trimmed')


if __name__ == '__main__':
    main()
