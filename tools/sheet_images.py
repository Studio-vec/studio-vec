"""Measure every image used in covers/sheets.js and write covers/sheet-images.js.

    python tools/sheet_images.py

For each image: aspect ratio, plus the uniform padding baked into the file
(black/grey bands from the web slides) so the A4 sheets can trim it.
Re-run after adding or changing images in sheets.js.
"""
import json, re
from pathlib import Path
from PIL import Image, ImageStat

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'covers' / 'sheets.js'
OUT = ROOT / 'covers' / 'sheet-images.js'
MAX_TRIM = 0.32          # never trim more than this per side
TOL = 7                  # spread allowed inside a dark band
FLAT = 1.2               # spread of a digitally flat band (photos have more grain than this)
DARK = 70                # a band this dark counts as padding even with a little noise


def band(im, side):
    """fraction of the image, from `side`, that is one flat colour"""
    w, h = im.size
    n = h if side in 'tb' else w
    edge = None
    limit = int(n * MAX_TRIM)
    for k in range(limit):
        if side == 't': box = (0, k, w, k + 1)
        elif side == 'b': box = (0, h - k - 1, w, h - k)
        elif side == 'l': box = (k, 0, k + 1, h)
        else: box = (w - k - 1, 0, w - k, h)
        st = ImageStat.Stat(im.crop(box))
        mean = st.mean
        # padding = digitally flat (no photo grain) or a dark band; studio backdrops are left alone
        flat = max(st.stddev) <= FLAT
        dark = max(st.stddev) <= TOL and max(mean) < DARK
        if not (flat or dark): return k / n
        if edge is None: edge = mean
        elif max(abs(a - b) for a, b in zip(mean, edge)) > TOL: return k / n
    return limit / n


def measure(path):
    im = Image.open(path)
    im.seek(0)
    w, h = im.size
    small = im.convert('RGB')
    small.thumbnail((400, 400))
    t, b, l, r = (band(small, s) for s in 'tblr')
    if t + b > .7 or l + r > .7: t = b = l = r = 0   # mostly flat image — leave it alone
    # keep a hair of the padding so nothing touches the cut
    t, b, l, r = (max(0, x - .004) if x > .01 else 0 for x in (t, b, l, r))
    return {'a': round(w / h, 4), 't': [round(t, 4), round(r, 4), round(b, 4), round(l, 4)]}


def main():
    js = SRC.read_text(encoding='utf8')
    out = {}
    # walk projects in order: dir, then every s:'file' until the next dir
    cur = None
    for m in re.finditer(r"dir:'([^']+)'|\bs:'([^']+)'", js):
        if m.group(1): cur = m.group(1); continue
        f = m.group(2)
        key = f if f.startswith('/') else f'/assets/img/projects/{cur}/{f}'
        if key in out: continue
        p = ROOT / key.lstrip('/')
        if not p.exists():
            print('missing', key); continue
        out[key] = measure(p)
    OUT.write_text('/* generated by tools/sheet_images.py — aspect ratio + baked-in padding [top,right,bottom,left] */\n'
                   'const SHEET_IMG = ' + json.dumps(out, separators=(',', ':')) + ';\n', encoding='utf8')
    trimmed = sum(1 for v in out.values() if any(v['t']))
    print(len(out), 'images,', trimmed, 'with padding trimmed')


if __name__ == '__main__':
    main()
